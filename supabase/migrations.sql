-- 1. Create API Keys Table
CREATE TABLE IF NOT EXISTS public.api_keys (
    key TEXT PRIMARY KEY,
    owner_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    name TEXT DEFAULT 'Default Key',
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 2. Create Scam Analysis Table (For Spam Classifier App)
CREATE TABLE IF NOT EXISTS public.scam_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT UNIQUE,
    domain TEXT,
    full_report JSONB,
    verdict TEXT,
    risk_score INT,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 3. Enable RLS (Row Level Security)
ALTER TABLE public.api_keys ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.scam_analysis ENABLE ROW LEVEL SECURITY;

-- 4. Create Policies (Initial permissive policies for getting started)
-- Note: In production, you should restrict these further based on your needs.

CREATE POLICY "Users can manage their own API keys" 
ON public.api_keys 
FOR ALL 
TO authenticated 
USING (auth.uid() = owner_id);

CREATE POLICY "Service can read/write analysis results" 
ON public.scam_analysis 
FOR ALL 
TO authenticated, anon, service_role 
USING (true) 
WITH CHECK (true);
